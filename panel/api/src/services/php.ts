/**
 * Multiple PHP versions side by side (packages from the Ondřej Surý repository, added by
 * the installer). Each site picks its version; its FPM pool lives in that version's pool.d.
 */
import { existsSync, readdirSync } from 'node:fs';
import { config } from '../config.ts';
import { all, getSetting, setSetting } from '../db.ts';
import { exec, tryExec } from '../lib/exec.ts';
import type { JobLog } from './jobs.ts';
import { checkPhp, PHP2SHELL_CVES } from './phpsecurity.ts';

export const SUPPORTED_PHP = ['7.4', '8.0', '8.1', '8.2', '8.3', '8.4', '8.5'] as const;
export const PHP_EXTENSIONS = ['cli', 'fpm', 'mysql', 'sqlite3', 'gd', 'intl', 'mbstring', 'xml', 'zip', 'curl', 'bcmath', 'opcache', 'readline'];
const OPTIONAL_EXTENSIONS = ['imagick', 'redis', 'apcu'];

const devInstalled = new Set<string>([config.phpVersion, '8.2']);

export const phpService = (v: string) => `php${v}-fpm`;
export const phpPoolDir = (v: string) => `/etc/php/${v}/fpm/pool.d`;

export function installedPhpVersions(): string[] {
  if (config.dev) return [...devInstalled].sort();
  try {
    return readdirSync('/etc/php')
      .filter((v) => /^\d+\.\d+$/.test(v) && existsSync(`/usr/sbin/php-fpm${v}`))
      .sort((a, b) => Number(a) - Number(b));
  } catch {
    return [];
  }
}

export function defaultPhpVersion(): string {
  const v = getSetting('php_default');
  const installed = installedPhpVersions();
  if (v && installed.includes(v)) return v;
  return installed.includes(config.phpVersion) ? config.phpVersion : (installed.at(-1) ?? config.phpVersion);
}

export function setDefaultPhpVersion(v: string) {
  if (!installedPhpVersions().includes(v)) throw new Error(`PHP ${v} no está instalado`);
  setSetting('php_default', v);
}

/** The version a site runs: its own choice if installed, otherwise the default. */
export function sitePhpVersion(site: { php_version: string }) {
  return site.php_version && installedPhpVersions().includes(site.php_version) ? site.php_version : defaultPhpVersion();
}

export function phpUsage(): Record<string, number> {
  const rows = all<{ php_version: string }>("SELECT php_version FROM sites WHERE type = 'php'");
  const usage: Record<string, number> = {};
  for (const r of rows) {
    const v = sitePhpVersion(r);
    usage[v] = (usage[v] ?? 0) + 1;
  }
  return usage;
}

/** apt output in English, so it can be parsed whatever the server's language. */
const APT_PARSE_ENV = { LC_ALL: 'C', LANG: 'C' };

/** Installable version of a package ("" if none: unknown or only mentioned by other packages). */
async function aptCandidate(pkg: string) {
  const r = await tryExec('apt-cache', ['policy', pkg], { env: APT_PARSE_ENV });
  const m = /Candidate:\s*(\S+)/.exec(r.output);
  return m && m[1] !== '(none)' ? m[1] : '';
}

/**
 * Packages to install for a version: only those that exist. Releases differ (since PHP 8.5 OPcache
 * is built in, so there is no phpX.Y-opcache), and fpm and cli are the only ones required.
 */
async function packagesFor(v: string) {
  const pkgs: string[] = [];
  for (const e of [...PHP_EXTENSIONS, ...OPTIONAL_EXTENSIONS]) {
    if (await aptCandidate(`php${v}-${e}`)) pkgs.push(`php${v}-${e}`);
  }
  for (const required of ['fpm', 'cli']) {
    if (!pkgs.includes(`php${v}-${required}`)) throw new Error(`No hay paquete php${v}-${required} para este sistema`);
  }
  return pkgs;
}

const APT_ENV = { DEBIAN_FRONTEND: 'noninteractive' };
const APT_OPTS = ['-y', '--no-install-recommends', '-o', 'Dpkg::Options::=--force-confdef', '-o', 'Dpkg::Options::=--force-confold'];

/** Performance defaults written for every version (opcache sized for many sites). */
const TUNING_INI = `; Generated by HostPanel.
opcache.enable=1
opcache.memory_consumption=192
opcache.interned_strings_buffer=16
opcache.max_accelerated_files=20000
opcache.validate_timestamps=1
opcache.revalidate_freq=2
realpath_cache_size=4096K
realpath_cache_ttl=600
expose_php=Off
; PHP2Shell follow-up (CVE-2026-115560): upload progress tracking stays off.
session.upload_progress.enabled=0
`;

const HARDENING_MARK = 'session.upload_progress.enabled=0';

async function writeTuning(v: string) {
  const { writeFile } = await import('node:fs/promises');
  for (const sapi of ['fpm', 'cli']) {
    const dir = `/etc/php/${v}/${sapi}/conf.d`;
    if (existsSync(dir)) await writeFile(`${dir}/99-hostpanel.ini`, TUNING_INI);
  }
}

/** Start-up: versions installed before the hardening get the current settings. */
export async function ensurePhpHardening() {
  if (config.dev) return;
  const { readFile } = await import('node:fs/promises');
  for (const v of installedPhpVersions()) {
    const ini = await readFile(`/etc/php/${v}/fpm/conf.d/99-hostpanel.ini`, 'utf8').catch(() => '');
    if (ini.includes(HARDENING_MARK)) continue;
    await writeTuning(v);
    await tryExec('systemctl', ['reload', phpService(v)]);
  }
}

/** Upstream version apt would install, e.g. "1:8.4.27-1+ubuntu24.04.1+deb.sury.org+1" → "8.4.27". */
async function candidateVersion(v: string) {
  const c = await aptCandidate(`php${v}-fpm`);
  return /^(?:\d+:)?([0-9.]+)/.exec(c)?.[1] ?? '';
}

/** Refuses (and removes) a build without the PHP2Shell fix. */
async function assertFixed(v: string, log: JobLog) {
  const sec = await checkPhp(v);
  if (sec.patched) {
    log(`✔ PHP ${sec.version}: PHP2Shell corregido${sec.via === 'backport' ? ' (parche de la distribución)' : ''}`);
    return;
  }
  log(`✖ PHP ${sec.version || v} no tiene corregido PHP2Shell (${PHP2SHELL_CVES.join(', ')}): se desinstala.`);
  await tryExec('systemctl', ['disable', '--now', phpService(v)]);
  await tryExec('apt-get', ['purge', '-y', `php${v}-*`], { env: APT_ENV });
  throw new Error(`Los paquetes de PHP ${v} disponibles para este servidor no tienen corregida la vulnerabilidad PHP2Shell. Elige otra versión.`);
}

export async function installPhp(v: string, log: JobLog) {
  if (!SUPPORTED_PHP.includes(v as (typeof SUPPORTED_PHP)[number])) throw new Error(`Versión no soportada: ${v}`);
  if (config.dev) {
    log(`[dev] apt-get install php${v}-fpm …`);
    await new Promise((r) => setTimeout(r, 1500));
    devInstalled.add(v);
    return;
  }
  log('$ apt-get update');
  await exec('apt-get', ['update'], { onLine: log, env: APT_ENV, timeoutMs: 5 * 60_000 });
  const candidate = await candidateVersion(v);
  if (!candidate) throw new Error(`No hay paquetes de PHP ${v} para este sistema`);
  log(`Versión disponible: ${candidate}`);
  const pkgs = await packagesFor(v);
  log(`$ apt-get install ${pkgs.join(' ')}`);
  await exec('apt-get', ['install', ...APT_OPTS, ...pkgs], { onLine: log, env: APT_ENV, timeoutMs: 20 * 60_000 });
  // Older branches or distribution builds may only carry the fix as a backport: check what got installed.
  await assertFixed(v, log);
  const { writeFile } = await import('node:fs/promises');
  await writeTuning(v);
  // The distro's default "www" pool is not used; HostPanel creates one pool per site.
  await tryExec('rm', ['-f', `${phpPoolDir(v)}/www.conf`]);
  // FPM refuses to start with zero pools: keep a tiny idle pool.
  await writeFile(
    `${phpPoolDir(v)}/hp-idle.conf`,
    `; Generated by HostPanel: keeps FPM running when no site uses this version.\n[hp-idle-${v.replace('.', '')}]\nuser = nobody\ngroup = nogroup\nlisten = /run/php/hp-idle-${v}.sock\npm = ondemand\npm.max_children = 1\n`,
  );
  await exec('systemctl', ['enable', '--now', phpService(v)], { onLine: log });
  await exec('systemctl', ['restart', phpService(v)], { onLine: log });
  log(`✔ PHP ${v} instalado y en marcha`);
}

/** Brings an installed version up to the latest packaged build (e.g. to get the PHP2Shell fix). */
export async function upgradePhp(v: string, log: JobLog) {
  if (!installedPhpVersions().includes(v)) throw new Error(`PHP ${v} no está instalado`);
  if (config.dev) {
    log(`[dev] apt-get install --only-upgrade php${v}-*`);
    await new Promise((r) => setTimeout(r, 1200));
    await checkPhp(v);
    return;
  }
  log('$ apt-get update');
  await exec('apt-get', ['update'], { onLine: log, env: APT_ENV, timeoutMs: 5 * 60_000 });
  const list = await tryExec('dpkg-query', ['-W', '-f=${Package}\n', `php${v}-*`]);
  const pkgs = list.output.split('\n').map((x) => x.trim()).filter((x) => /^php\d+\.\d+-[a-z0-9-]+$/.test(x));
  log(`$ apt-get install --only-upgrade ${pkgs.join(' ')}`);
  await exec('apt-get', ['install', '--only-upgrade', ...APT_OPTS, ...pkgs], { onLine: log, env: APT_ENV, timeoutMs: 20 * 60_000 });
  await writeTuning(v);
  await exec('systemctl', ['restart', phpService(v)], { onLine: log });
  const sec = await checkPhp(v);
  if (sec.patched) log(`✔ PHP ${sec.version}: PHP2Shell corregido`);
  else throw new Error(`PHP ${v} sigue sin el parche de PHP2Shell (versión ${sec.version}). Tu repositorio aún no publica la corrección: cambia los sitios a otra versión.`);
}

export async function removePhp(v: string, log: JobLog) {
  if (phpUsage()[v]) throw new Error(`Hay sitios usando PHP ${v}. Cámbialos de versión antes de desinstalarla.`);
  if (v === defaultPhpVersion()) throw new Error('No puedes desinstalar la versión por defecto.');
  if (v === config.phpVersion) throw new Error('Esta versión la usa el webmail (Roundcube).');
  if (config.dev) {
    devInstalled.delete(v);
    log(`[dev] apt-get purge php${v}-*`);
    return;
  }
  await tryExec('systemctl', ['disable', '--now', phpService(v)]);
  log(`$ apt-get purge php${v}-*`);
  await exec('apt-get', ['purge', '-y', `php${v}-*`], { onLine: log, env: APT_ENV, timeoutMs: 10 * 60_000 });
  await tryExec('apt-get', ['autoremove', '-y'], { env: APT_ENV });
  log(`✔ PHP ${v} desinstalado`);
}

export async function reloadPhpVersion(v: string) {
  await exec('systemctl', ['reload', phpService(v)]);
}
