/**
 * MariaDB management through the local unix socket (root uses unix_socket auth), plus a
 * D1-style layer: SQL console, table browser, HTTP query API, export/import.
 * Queries from the console/API run as the database's own user (never as root).
 */
import { spawn } from 'node:child_process';
import { existsSync, mkdirSync } from 'node:fs';
import { writeFile, rm } from 'node:fs/promises';
import { join } from 'node:path';
import { DatabaseSync } from 'node:sqlite';
import { PassThrough, type Readable } from 'node:stream';
import { pipeline } from 'node:stream/promises';
import mysql from 'mysql2/promise';
import { config } from '../config.ts';
import type { DatabaseRow } from '../db.ts';
import { decrypt } from '../lib/crypto.ts';
import { exec, tryExec } from '../lib/exec.ts';
import { HttpError } from '../lib/validate.ts';

async function withRoot<T>(fn: (conn: mysql.Connection) => Promise<T>): Promise<T> {
  if (config.dev) return undefined as T;
  let conn: mysql.Connection;
  try {
    conn = await mysql.createConnection({ socketPath: config.mysqlSocket, user: 'root' });
  } catch {
    throw new HttpError(502, 'No se pudo conectar con MariaDB');
  }
  try {
    return await fn(conn);
  } finally {
    await conn.end();
  }
}

// Names are validated with a strict regex before reaching here; identifiers are also escaped.
const ident = (s: string) => `\`${s.replace(/`/g, '')}\``;

export async function createDatabase(name: string, username: string, password: string) {
  if (config.dev) devDb(name);
  await withRoot(async (c) => {
    await c.query(`CREATE DATABASE ${ident(name)} CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci`);
    await c.query('CREATE USER IF NOT EXISTS ?@? IDENTIFIED BY ?', [username, 'localhost', password]);
    await c.query(`GRANT ALL PRIVILEGES ON ${ident(name)}.* TO ?@?`, [username, 'localhost']);
    await c.query('FLUSH PRIVILEGES');
  });
}

export async function dropDatabase(name: string, username: string, remoteHosts: string[] = []) {
  if (config.dev) {
    devDbs.get(name)?.close();
    devDbs.delete(name);
    await rm(join(config.dataDir, `devdb-${name}.sqlite`), { force: true });
  }
  await withRoot(async (c) => {
    await c.query(`DROP DATABASE IF EXISTS ${ident(name)}`);
    for (const host of ['localhost', ...remoteHosts]) await c.query('DROP USER IF EXISTS ?@?', [username, host]);
  });
  for (const host of remoteHosts) await firewall3306(host, false);
}

export async function resetDatabasePassword(username: string, password: string, remoteHosts: string[] = []) {
  await withRoot(async (c) => {
    for (const host of ['localhost', ...remoteHosts]) await c.query('ALTER USER ?@? IDENTIFIED BY ?', [username, host, password]);
  });
}

export async function databaseSizes(): Promise<Record<string, number>> {
  const rows = await withRoot(async (c) => {
    const [r] = await c.query(
      'SELECT table_schema AS name, SUM(data_length + index_length) AS size FROM information_schema.tables GROUP BY table_schema',
    );
    return r as { name: string; size: number }[];
  });
  return Object.fromEntries((rows ?? []).map((r) => [r.name, Number(r.size)]));
}

// --- remote access (apps on other VPS) -------------------------------------------------

const REMOTE_CNF = '/etc/mysql/mariadb.conf.d/91-hostpanel-remote.cnf';

async function firewall3306(host: string, allow: boolean) {
  const args = allow ? ['allow', 'from', host, 'to', 'any', 'port', '3306', 'proto', 'tcp'] : ['delete', 'allow', 'from', host, 'to', 'any', 'port', '3306', 'proto', 'tcp'];
  await tryExec('ufw', args);
}

/** Lets the database user connect from the given IPs (one MariaDB account per host). */
export async function setRemoteHosts(db: DatabaseRow, hosts: string[]) {
  const previous = JSON.parse(db.remote_hosts) as string[];
  const password = db.password_enc ? decrypt(db.password_enc) : '';
  if (hosts.length && !password) throw new HttpError(400, 'Genera una nueva contraseña antes de activar el acceso remoto');
  if (hosts.length && !config.dev && !existsSync(REMOTE_CNF)) {
    // MariaDB listens only on localhost by default; the firewall still blocks 3306.
    await writeFile(REMOTE_CNF, '# Generated by HostPanel: remote access for allowed IPs (filtered by UFW).\n[mysqld]\nbind-address = 0.0.0.0\n');
    await exec('systemctl', ['restart', 'mariadb']);
  }
  await withRoot(async (c) => {
    for (const host of previous.filter((h) => !hosts.includes(h))) await c.query('DROP USER IF EXISTS ?@?', [db.username, host]);
    for (const host of hosts) {
      await c.query('CREATE USER IF NOT EXISTS ?@? IDENTIFIED BY ?', [db.username, host, password]);
      await c.query('ALTER USER ?@? IDENTIFIED BY ?', [db.username, host, password]);
      await c.query(`GRANT ALL PRIVILEGES ON ${ident(db.name)}.* TO ?@?`, [db.username, host]);
    }
    await c.query('FLUSH PRIVILEGES');
  });
  for (const host of previous.filter((h) => !hosts.includes(h))) await firewall3306(host, false);
  for (const host of hosts) await firewall3306(host, true);
}

// --- D1-style query layer ---------------------------------------------------------------

export interface QueryResult {
  columns: string[];
  rows: unknown[][];
  rowCount: number;
  affectedRows: number;
  insertId: number | null;
  durationMs: number;
  truncated: boolean;
}

const devDbs = new Map<string, DatabaseSync>();
function devDb(name: string) {
  let d = devDbs.get(name);
  if (!d) {
    mkdirSync(config.dataDir, { recursive: true });
    d = new DatabaseSync(join(config.dataDir, `devdb-${name}.sqlite`));
    devDbs.set(name, d);
  }
  return d;
}

async function withUser<T>(db: DatabaseRow, fn: (conn: mysql.Connection) => Promise<T>): Promise<T> {
  if (!db.password_enc) throw new HttpError(400, 'Esta base de datos no tiene la contraseña guardada: genera una nueva para usar la consola y la API.');
  let conn: mysql.Connection;
  try {
    conn = await mysql.createConnection({
      socketPath: config.mysqlSocket,
      user: db.username,
      password: decrypt(db.password_enc),
      database: db.name,
      dateStrings: true,
      supportBigNumbers: true,
      bigNumberStrings: true,
      multipleStatements: false,
    });
  } catch (err) {
    throw new HttpError(502, `No se pudo conectar como ${db.username}: ${(err as Error).message}`);
  }
  try {
    return await fn(conn);
  } finally {
    await conn.end();
  }
}

type Param = string | number | boolean | null;

function toResult(raw: unknown, fields: { name: string }[] | undefined, started: number, maxRows: number): QueryResult {
  const durationMs = Math.round((performance.now() - started) * 10) / 10;
  if (Array.isArray(raw)) {
    const rows = raw as unknown[][];
    return {
      columns: (fields ?? []).map((f) => f.name),
      rows: rows.slice(0, maxRows),
      rowCount: rows.length,
      affectedRows: 0,
      insertId: null,
      durationMs,
      truncated: rows.length > maxRows,
    };
  }
  const h = raw as { affectedRows?: number; insertId?: number };
  return { columns: [], rows: [], rowCount: 0, affectedRows: h.affectedRows ?? 0, insertId: h.insertId || null, durationMs, truncated: false };
}

function devQuery(db: DatabaseRow, sql: string, params: Param[], maxRows: number): QueryResult {
  const started = performance.now();
  const stmt = devDb(db.name).prepare(sql);
  const p = params.map((v) => (typeof v === 'boolean' ? Number(v) : v));
  if (/^\s*(select|pragma|with|explain)\b/i.test(sql)) {
    const rows = stmt.all(...p) as Record<string, unknown>[];
    const columns = rows[0] ? Object.keys(rows[0]) : stmt.columns().map((c) => c.name);
    return toResult(rows.map((r) => columns.map((c) => r[c])), columns.map((name) => ({ name })), started, maxRows);
  }
  const r = stmt.run(...p);
  return toResult({ affectedRows: Number(r.changes), insertId: Number(r.lastInsertRowid) }, undefined, started, maxRows);
}

export async function runQuery(db: DatabaseRow, sql: string, params: Param[] = [], maxRows = 1000, readOnly = false): Promise<QueryResult> {
  if (config.dev) {
    try {
      return devQuery(db, sql, params, maxRows);
    } catch (err) {
      throw new HttpError(400, (err as Error).message);
    }
  }
  return withUser(db, async (c) => {
    if (readOnly) await c.query('SET SESSION TRANSACTION READ ONLY');
    const started = performance.now();
    try {
      const [raw, fields] = await c.query({ sql, rowsAsArray: true }, params);
      return toResult(raw, fields as { name: string }[] | undefined, started, maxRows);
    } catch (err) {
      throw new HttpError(400, (err as Error).message);
    }
  });
}

/** Several statements in one transaction (all or nothing), like D1's batch(). */
export async function runBatch(db: DatabaseRow, statements: { sql: string; params?: Param[] }[], readOnly = false): Promise<QueryResult[]> {
  if (config.dev) {
    const d = devDb(db.name);
    d.exec('BEGIN');
    try {
      const out = statements.map((s) => devQuery(db, s.sql, s.params ?? [], 1000));
      d.exec('COMMIT');
      return out;
    } catch (err) {
      d.exec('ROLLBACK');
      throw new HttpError(400, (err as Error).message);
    }
  }
  return withUser(db, async (c) => {
    if (readOnly) await c.query('SET SESSION TRANSACTION READ ONLY');
    await c.beginTransaction();
    try {
      const out: QueryResult[] = [];
      for (const s of statements) {
        const started = performance.now();
        const [raw, fields] = await c.query({ sql: s.sql, rowsAsArray: true }, s.params ?? []);
        out.push(toResult(raw, fields as { name: string }[] | undefined, started, 1000));
      }
      await c.commit();
      return out;
    } catch (err) {
      await c.rollback().catch(() => {});
      throw new HttpError(400, (err as Error).message);
    }
  });
}

export async function listTables(db: DatabaseRow) {
  if (config.dev) {
    const rows = devDb(db.name).prepare("SELECT name FROM sqlite_master WHERE type = 'table' AND name NOT LIKE 'sqlite_%' ORDER BY name").all() as { name: string }[];
    return rows.map((r) => ({
      name: r.name,
      rows: Number((devDb(db.name).prepare(`SELECT COUNT(*) n FROM "${r.name.replace(/"/g, '')}"`).get() as { n: number }).n),
      size: 0,
      engine: 'SQLite (dev)',
    }));
  }
  return withRoot(async (c) => {
    const [rows] = await c.query(
      `SELECT table_name AS name, table_rows AS \`rows\`, data_length + index_length AS size, engine
       FROM information_schema.tables WHERE table_schema = ? ORDER BY table_name`,
      [db.name],
    );
    return (rows as { name: string; rows: number; size: number; engine: string }[]).map((r) => ({ ...r, rows: Number(r.rows), size: Number(r.size) }));
  });
}

export async function browseTable(db: DatabaseRow, table: string, page: number, pageSize = 50) {
  const tables = await listTables(db);
  if (!tables.some((t) => t.name === table)) throw new HttpError(404, 'Tabla no encontrada');
  const q = config.dev ? `"${table.replace(/"/g, '')}"` : ident(table);
  return runQuery(db, `SELECT * FROM ${q} LIMIT ${pageSize} OFFSET ${Math.max(0, page) * pageSize}`, [], pageSize);
}

/** Streams a full SQL dump (structure + data, consistent snapshot). */
export function exportDatabase(name: string): Readable {
  if (config.dev) {
    const out = new PassThrough();
    out.end(`-- HostPanel (modo desarrollo): exportación simulada de ${name}\n`);
    return out;
  }
  const child = spawn('mariadb-dump', ['--single-transaction', '--quick', '--routines', '--triggers', '--events', '--default-character-set=utf8mb4', name], {
    stdio: ['ignore', 'pipe', 'pipe'],
  });
  child.stderr.on('data', (d) => console.error(`mariadb-dump ${name}: ${String(d).trim()}`));
  return child.stdout;
}

/**
 * Runs an uploaded .sql file against the database. It runs as the database's own user
 * when its password is stored, so a crafted file cannot touch other databases.
 */
export async function importDatabase(db: DatabaseRow, body: Readable) {
  if (config.dev) {
    body.resume();
    return;
  }
  const asUser = db.password_enc ? ['-u', db.username] : [];
  const env = db.password_enc ? { ...process.env, MYSQL_PWD: decrypt(db.password_enc) } : process.env;
  const child = spawn('mariadb', [...asUser, '--default-character-set=utf8mb4', db.name], { stdio: ['pipe', 'ignore', 'pipe'], env });
  let stderr = '';
  child.stderr.on('data', (d) => (stderr += String(d)));
  const done = new Promise<number>((resolve) => child.on('close', resolve));
  await pipeline(body, child.stdin).catch(() => {});
  const code = await done;
  if (code !== 0) throw new HttpError(400, `La importación falló: ${stderr.trim().slice(0, 500)}`);
}
