/**
 * Secondary nameserver: ns2 on another machine, so domains keep resolving if this server goes
 * down. The other machine runs dns-secondary.sh (PowerDNS as secondary with "autosecondary").
 *
 *   this server (primary)  zones of kind Master; replication settings in
 *                          /etc/powerdns/pdns.d/hostpanel-replication.conf: AXFR allowed and
 *                          NOTIFY sent to the secondary's IP
 *   secondary              accepts NOTIFY only from this server, transfers every zone (and new
 *                          ones automatically) and answers as ns2.<main domain>
 *
 * Adding it also points ns2 (A/AAAA in the main domain and the glue at the registrar) to it.
 */
import { appendFileSync, existsSync, readdirSync, readFileSync, renameSync, rmSync, writeFileSync } from 'node:fs';
import { Resolver } from 'node:dns/promises';
import { isIPv4, isIPv6 } from 'node:net';
import { config } from '../config.ts';
import { all, run, setSetting } from '../db.ts';
import { exec } from '../lib/exec.ts';
import { HttpError } from '../lib/validate.ts';
import * as dns from './dns.ts';
import { publishServerHosts } from './identity.ts';
import { isPrivateIp } from './setup.ts';

const PDNS_CONF = '/etc/powerdns/pdns.conf';
const PDNS_INCLUDE_DIR = '/etc/powerdns/pdns.d';
const REPLICATION_CONF = `${PDNS_INCLUDE_DIR}/hostpanel-replication.conf`;

export const SECONDARY_SCRIPT = 'dns-secondary.sh';

function managedZones() {
  return all<{ name: string }>('SELECT name FROM domains WHERE dns_enabled = 1 ORDER BY name').map((d) => d.name);
}

/** Older installs wrote pdns.conf without include-dir: add it so the replication file is read. */
function ensureIncludeDir() {
  const conf = readFileSync(PDNS_CONF, 'utf8');
  if (/^\s*include-dir\s*=/m.test(conf)) return;
  // Files the distribution may have left there (other backends) must not be loaded.
  for (const f of readdirSync(PDNS_INCLUDE_DIR)) {
    if (f.endsWith('.conf') && !f.startsWith('hostpanel-')) renameSync(`${PDNS_INCLUDE_DIR}/${f}`, `${PDNS_INCLUDE_DIR}/${f}.disabled-by-hostpanel`);
  }
  appendFileSync(PDNS_CONF, `\n# Added by HostPanel: extra settings (secondary nameserver).\ninclude-dir=${PDNS_INCLUDE_DIR}\n`);
}

async function writeReplication(ips: string[]) {
  if (config.dev) return;
  if (ips.length) {
    ensureIncludeDir();
    writeFileSync(
      REPLICATION_CONF,
      `# Generated by HostPanel: zones are transferred to the secondary nameserver.\nprimary=yes\nallow-axfr-ips=127.0.0.1,::1,${ips.join(',')}\nalso-notify=${ips.join(',')}\n`,
      { mode: 0o640 },
    );
    await exec('chown', ['root:pdns', REPLICATION_CONF]);
  } else if (existsSync(REPLICATION_CONF)) {
    rmSync(REPLICATION_CONF);
  }
  await exec('systemctl', ['restart', 'pdns']);
  // PowerDNS needs a moment before its API answers again.
  for (let i = 0; i < 20; i++) {
    try {
      await dns.listZones();
      return;
    } catch {
      await new Promise((r) => setTimeout(r, 500));
    }
  }
}

function resolverFor(ip: string) {
  const r = new Resolver({ timeout: 3000, tries: 1 });
  r.setServers([ip]);
  return r;
}

/** True when something answers DNS on the IP (an authoritative server refusing a zone still answers). */
async function answersDns(ip: string) {
  if (config.dev) return true;
  try {
    await resolverFor(ip).resolveSoa(config.baseDomain || 'example.com');
    return true;
  } catch (err) {
    const code = (err as { code?: string }).code ?? '';
    return !['ETIMEOUT', 'ECONNREFUSED', 'ECONNRESET', 'EHOSTUNREACH'].includes(code);
  }
}

export async function enableSecondary(input: { ip: string; ipv6?: string | null }) {
  const ip = input.ip.trim();
  const ipv6 = input.ipv6?.trim() || null;
  if (!isIPv4(ip)) throw new HttpError(400, 'Escribe la IPv4 pública del servidor secundario');
  if (ipv6 && !isIPv6(ipv6)) throw new HttpError(400, 'La IPv6 no es válida');
  if (isPrivateIp(ip)) throw new HttpError(400, 'Esa IP es privada: los registradores necesitan la IP pública del secundario');
  if (ip === config.serverIp || ip === config.localIp) throw new HttpError(400, 'Esa es la IP de este servidor: el secundario debe estar en otra máquina');
  if (!config.baseDomain || !config.ns2.endsWith(`.${config.baseDomain}`)) {
    throw new HttpError(400, 'Configura primero el dominio principal del servidor (Ajustes)');
  }
  if (!(await answersDns(ip))) {
    throw new HttpError(400, `${ip} no responde en el puerto 53. Ejecuta primero el comando de instalación en esa máquina.`);
  }
  await writeReplication([ip, ...(ipv6 ? [ipv6] : [])]);
  setSetting('dns_secondary', JSON.stringify({ ip, ipv6, added_at: new Date().toISOString() }));
  const zones = managedZones();
  for (const z of zones) await dns.setZoneKind(z, 'Master').catch((err) => console.error(`Zona ${z}: ${(err as Error).message}`));
  await publishServerHosts(config.baseDomain);
  for (const z of zones) await dns.notifyZone(z).catch(() => {});
  return secondaryStatus();
}

export async function disableSecondary() {
  await writeReplication([]);
  run("DELETE FROM settings WHERE key = 'dns_secondary'");
  if (config.baseDomain) await publishServerHosts(config.baseDomain);
}

/** Zones the secondary already serves, with the same serial as here (= up to date). */
export async function secondaryStatus() {
  const sec = dns.secondaryDns();
  const base = {
    configured: !!sec,
    secondary: sec,
    ns2: config.ns2,
    primary_ip: config.serverIp,
    ready: !!config.baseDomain && config.ns2.endsWith(`.${config.baseDomain}`),
  };
  if (!sec) return { ...base, reachable: null, zones: [] };
  const zones = managedZones();
  const resolver = resolverFor(sec.ip);
  const reachable = await answersDns(sec.ip);
  const rows = [];
  for (const name of zones) {
    const primary = await dns.zoneSerial(name).catch(() => null);
    let secondary: number | null = null;
    if (config.dev) secondary = primary;
    else if (reachable) secondary = await resolver.resolveSoa(name).then((s) => s.serial).catch(() => null);
    rows.push({ name, primary_serial: primary, secondary_serial: secondary, in_sync: primary !== null && primary === secondary });
  }
  return { ...base, reachable, zones: rows };
}

/** Sends every zone again (button "Sincronizar ahora"). */
export async function resyncSecondary() {
  for (const z of managedZones()) await dns.notifyZone(z).catch(() => {});
}
