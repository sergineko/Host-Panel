/**
 * SFTP-only accounts per site (cPanel's "FTP Accounts", but encrypted).
 *
 * Each account is a Linux user that shares the site user's UID/GID (`useradd -o`), so files
 * it uploads belong to the site exactly as if the site had written them. OpenSSH locks the
 * account in with `internal-sftp` + `ChrootDirectory`: no shell, no port forwarding and no
 * view outside the site's folder. The site folder itself is root-owned (OpenSSH requires it).
 */
import { mkdir, readFile } from 'node:fs/promises';
import { join } from 'node:path';
import { config } from '../config.ts';
import { exec, tryExec } from '../lib/exec.ts';
import { ensureSiteUser, lockSiteRoot, removeSystemFile, sitePaths, siteUser, writeSystemFile } from './system.ts';

export const SFTP_GROUP = 'hostpanel-sftp';
const SSHD_DROPIN = '/etc/ssh/sshd_config.d/10-hostpanel-sftp.conf';
const KEYS_DIR = '/etc/ssh/hostpanel-keys';

/** Linux user names: lowercase, start with a letter, max 32 chars. */
export const SFTP_USERNAME_RE = /^[a-z][a-z0-9_-]{2,31}$/;
/** Names that already mean something on a server. */
const RESERVED = new Set(['root', 'admin', 'caddy', 'www-data', 'mysql', 'postgres', 'redis', 'stalwart', 'pdns', 'hostpanel', 'ubuntu', 'debian', 'nobody', 'sshd', 'daemon', 'mail', 'ftp', 'sftp', 'backup', 'operator', 'sync', 'git']);

export function sftpUsernameProblem(name: string): string | null {
  if (!SFTP_USERNAME_RE.test(name)) return 'Usa de 3 a 32 caracteres: minúsculas, números, «-» o «_», empezando por una letra';
  if (RESERVED.has(name) || name.startsWith('hp-') || name.startsWith('systemd')) return 'Ese nombre está reservado para el sistema';
  return null;
}

const SSHD_CONFIG = `# Generated by HostPanel. Do not edit.
# Members of ${SFTP_GROUP} get SFTP only, locked inside their site's folder.
Match Group ${SFTP_GROUP}
    ChrootDirectory %h
    ForceCommand internal-sftp -d /current
    PasswordAuthentication yes
    PubkeyAuthentication yes
    AuthorizedKeysFile ${KEYS_DIR}/%u
    AllowTcpForwarding no
    AllowStreamLocalForwarding no
    AllowAgentForwarding no
    X11Forwarding no
    PermitTunnel no
    PermitTTY no
    PermitUserRC no
# Back to global settings for anything that follows.
Match all
`;

/** Group, keys folder and sshd drop-in. Idempotent; reloads sshd only when its config changes. */
export async function ensureSftpSetup() {
  if (!(await tryExec('getent', ['group', SFTP_GROUP])).ok) await exec('groupadd', ['--system', SFTP_GROUP]);
  if (!config.dev) await mkdir(KEYS_DIR, { recursive: true, mode: 0o755 });
  const current = config.dev ? '' : await readFile(SSHD_DROPIN, 'utf8').catch(() => '');
  if (current === SSHD_CONFIG) return;
  await writeSystemFile(SSHD_DROPIN, SSHD_CONFIG);
  // Never reload sshd with a broken config: that could lock everyone out.
  const test = await tryExec('sshd', ['-t']);
  if (!test.ok) {
    await removeSystemFile(SSHD_DROPIN);
    throw new Error(`La configuración de SSH no es válida: ${test.output.trim()}`);
  }
  await reloadSshd();
}

async function reloadSshd() {
  // Debian/Ubuntu call the unit "ssh"; other distributions "sshd".
  if (!(await tryExec('systemctl', ['reload', 'ssh'])).ok) await exec('systemctl', ['reload', 'sshd']);
}

let cachedPort: number | null = null;
/** Port users connect to (read from sshd's effective config). */
export async function sshPort(): Promise<number> {
  if (cachedPort) return cachedPort;
  const r = config.dev ? { ok: false, output: '' } : await tryExec('sshd', ['-T']);
  const m = r.output.match(/^port (\d+)$/m);
  cachedPort = m ? Number(m[1]) : 22;
  return cachedPort;
}

/** True when a Linux user (or group) with that name already exists. */
export async function systemUserExists(name: string) {
  if (config.dev) return false;
  return (await tryExec('getent', ['passwd', name])).ok;
}

export async function setSftpPassword(username: string, password: string) {
  await exec('chpasswd', [], { input: `${username}:${password}\n`, mask: [password] });
}

/** One key per line; blank lines and comments are dropped. */
export function normalizeKeys(keys: string) {
  return keys
    .split(/\r?\n/)
    .map((l) => l.trim())
    .filter((l) => l && !l.startsWith('#'))
    .join('\n');
}

export const KEY_LINE_RE = /^(ssh-(ed25519|rsa|dss)|ecdsa-sha2-nistp(256|384|521)|sk-(ssh-ed25519|ecdsa-sha2-nistp256)@openssh\.com) [A-Za-z0-9+/=]{40,}( [^\n]{0,200})?$/;

export async function writeSftpKeys(username: string, keys: string) {
  const path = join(KEYS_DIR, username);
  // Root-owned and not writable by the user: sshd's StrictModes accepts it and the user can't add keys.
  if (keys) await writeSystemFile(path, `${keys}\n`, 0o644);
  else await removeSystemFile(path);
}

export async function createSftpUser(siteId: number, username: string, password: string, keys: string) {
  await ensureSftpSetup();
  await ensureSiteUser(siteId);
  await lockSiteRoot(siteId);
  const owner = siteUser(siteId);
  const uid = config.dev ? '0' : (await exec('id', ['-u', owner])).trim();
  await exec('useradd', [
    '--non-unique', '--uid', uid, // same UID as the site: uploads belong to the site
    '--gid', owner,
    '--groups', SFTP_GROUP,
    '--no-create-home', '--home-dir', sitePaths(siteId).root, // %h = chroot
    '--shell', '/usr/sbin/nologin',
    '--comment', `HostPanel SFTP site ${siteId}`,
    username,
  ]);
  try {
    await setSftpPassword(username, password);
    await writeSftpKeys(username, keys);
  } catch (err) {
    await removeSftpUser(username).catch(() => {});
    throw err;
  }
}

/**
 * Removes the login only. The UID is shared with the site, so we never use `userdel -r`
 * and point the home at "/" first: nothing of the site can be deleted by accident.
 */
export async function removeSftpUser(username: string) {
  await writeSftpKeys(username, '');
  if (!(await systemUserExists(username)) && !config.dev) return;
  // Close open sessions of this login (by process title, not UID: the UID is the site's).
  await tryExec('pkill', ['-KILL', '-f', `^sshd(-session)?: ${username}([ @]|$)`]);
  await tryExec('usermod', ['--home', '/', username]);
  // --force: the shared UID always has running processes (PHP, Node), which userdel would refuse.
  await exec('userdel', ['--force', username]);
}
